import { paraglideVitePlugin } from '@inlang/paraglide-js';
import { defineConfig } from 'vitest/config';
import { playwright } from '@vitest/browser-playwright';
import adapter from '@sveltejs/adapter-static';
import { sveltekit } from '@sveltejs/kit/vite';

// In development, `/files` is proxied to the local public bucket (Garage web endpoint), which picks
// the bucket from the Host header. In production the same keys are served by the CDN.
const filesOrigin = process.env.TM_PUBLIC_FILES_ORIGIN ?? 'http://localhost:3902';

export default defineConfig({
	plugins: [
		sveltekit({
			compilerOptions: {
				// Force runes mode for the project, except for libraries. Can be removed in svelte 6.
				runes: ({ filename }) =>
					filename.split(/[/\\]/).includes('node_modules') ? undefined : true
			},
			adapter: adapter({ fallback: undefined, strict: true }),
			prerender: { entries: ['*', '/fr'] }
		}),

		paraglideVitePlugin({
			project: './project.inlang',
			outdir: './src/lib/paraglide',
			emitTsDeclarations: true,
			// Static site: the locale lives in the URL (`/` English, `/fr/` French).
			strategy: ['url', 'baseLocale']
		})
	],
	server: {
		proxy: {
			'/files': {
				target: filesOrigin,
				rewrite: (path) => path.replace(/^\/files/, ''),
				headers: { Host: 'tm-public.web.localhost' }
			}
		}
	},
	test: {
		expect: { requireAssertions: true },
		projects: [
			{
				extends: './vite.config.ts',
				test: {
					name: 'client',
					browser: {
						enabled: true,
						provider: playwright(),
						instances: [{ browser: 'chromium', headless: true }]
					},
					include: ['src/**/*.svelte.{test,spec}.{js,ts}'],
					exclude: ['src/lib/server/**']
				}
			},

			{
				extends: './vite.config.ts',
				test: {
					name: 'server',
					environment: 'node',
					include: ['src/**/*.{test,spec}.{js,ts}'],
					exclude: ['src/**/*.svelte.{test,spec}.{js,ts}']
				}
			}
		]
	}
});
